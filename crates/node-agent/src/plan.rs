//! What the node runs, worked out from its configuration without touching the machine. Keeping
//! this pure is what lets the unit tests pin every security-relevant setting.

use std::path::{Path, PathBuf};

use crate::config::{NodeConfig, Role};

/// The administrator's database role. The agent gives it a password on first start.
pub const ADMIN_ROLE: &str = "ledger_admin";
/// The role standbys use. It has no password: it signs in with a client certificate.
pub const REPLICATION_ROLE: &str = "replicator";

/// Where things are. Everything but the data directory may live on a read-only root file system
/// with a small writable area mounted at `run`.
#[derive(Debug, Clone)]
pub struct Paths {
    /// PostgreSQL's binaries.
    pub bin: PathBuf,
    /// The data directory, on the node's encrypted volume.
    pub data: PathBuf,
    /// A writable area that does not need to survive a restart: the socket, generated files and
    /// the copy of the TLS files.
    pub run: PathBuf,
    /// The mounted TLS files: server.crt, server.key, ca.crt and, for a standby,
    /// replication.crt and replication.key.
    pub tls_in: PathBuf,
}

impl Paths {
    pub fn tls(&self) -> PathBuf {
        self.run.join("tls")
    }
    pub fn hba(&self) -> PathBuf {
        self.run.join("pg_hba.conf")
    }
    pub fn tool(&self, name: &str) -> PathBuf {
        self.bin.join(name)
    }
}

/// The files the agent needs under `tls_in`, for a role.
pub fn tls_files(role: Role) -> &'static [&'static str] {
    match role {
        Role::Primary => &["server.crt", "server.key", "ca.crt"],
        Role::Standby => &[
            "server.crt",
            "server.key",
            "ca.crt",
            "replication.crt",
            "replication.key",
        ],
    }
}

/// The access rules. The first rule that matches wins, and a connection that matches none is
/// refused, so there is no way in without TLS.
pub fn hba() -> String {
    format!(
        "\
# Generated by ledger-node. Do not edit.
local   all          {ADMIN_ROLE}                  scram-sha-256
local   all          all                           reject
hostssl replication  {REPLICATION_ROLE}  0.0.0.0/0  cert
hostssl replication  {REPLICATION_ROLE}  ::/0       cert
hostssl all          all   0.0.0.0/0  scram-sha-256
hostssl all          all   ::/0       scram-sha-256
"
    )
}

fn setting(name: &str, value: impl AsRef<str>) -> [String; 2] {
    ["-c".to_string(), format!("{name}={}", value.as_ref())]
}

/// The arguments for `postgres`. Nothing in them is secret.
pub fn server_args(config: &NodeConfig, paths: &Paths) -> Vec<String> {
    let tls = paths.tls();
    let mut args: Vec<String> = vec!["-D".into(), paths.data.display().to_string()];
    let mut add = |name: &str, value: String| args.extend(setting(name, value));

    add("listen_addresses", "*".into());
    add("port", config.port.to_string());
    add("unix_socket_directories", paths.run.display().to_string());
    add("hba_file", paths.hba().display().to_string());
    add("cluster_name", config.node.clone());

    add("ssl", "on".into());
    add(
        "ssl_cert_file",
        tls.join("server.crt").display().to_string(),
    );
    add("ssl_key_file", tls.join("server.key").display().to_string());
    add("ssl_ca_file", tls.join("ca.crt").display().to_string());
    add("ssl_min_protocol_version", "TLSv1.3".into());
    add("password_encryption", "scram-sha-256".into());

    // Physical streaming replication only. No slots of any kind, so no logical slots.
    add("wal_level", "replica".into());
    add("max_wal_senders", "10".into());
    add("max_replication_slots", "0".into());
    add("wal_keep_size", "1GB".into());
    add("wal_log_hints", "on".into());
    add("hot_standby", "on".into());
    add("synchronous_commit", "on".into());

    match config.role {
        Role::Primary => add(
            "synchronous_standby_names",
            config.synchronous_standby_names.clone(),
        ),
        Role::Standby => add("primary_conninfo", primary_conninfo(config, paths)),
    }
    args
}

/// How a standby reaches its primary: verified TLS, and a client certificate in place of a
/// password. `application_name` is the node's name, which the primary's list matches.
pub fn primary_conninfo(config: &NodeConfig, paths: &Paths) -> String {
    let tls = paths.tls();
    format!(
        "host={} port={} user={REPLICATION_ROLE} application_name={} sslmode=verify-full sslcert={} sslkey={} sslrootcert={}",
        config.primary_address,
        config.upstream_port(),
        config.node,
        tls.join("replication.crt").display(),
        tls.join("replication.key").display(),
        tls.join("ca.crt").display(),
    )
}

/// `pg_basebackup` arguments. No slot is used: the primary keeps a margin of WAL instead.
pub fn basebackup_args(config: &NodeConfig, paths: &Paths) -> Vec<String> {
    vec![
        "-h".into(),
        config.primary_address.clone(),
        "-p".into(),
        config.upstream_port().to_string(),
        "-U".into(),
        REPLICATION_ROLE.into(),
        "-D".into(),
        paths.data.display().to_string(),
        "-X".into(),
        "stream".into(),
        "--no-slot".into(),
        "-c".into(),
        "fast".into(),
        "--no-password".into(),
    ]
}

/// The environment `pg_basebackup` needs to verify the primary and present its certificate.
pub fn basebackup_env(paths: &Paths) -> Vec<(String, String)> {
    let tls = paths.tls();
    let p = |f: &str| tls.join(f).display().to_string();
    vec![
        ("PGSSLMODE".into(), "verify-full".into()),
        ("PGSSLCERT".into(), p("replication.crt")),
        ("PGSSLKEY".into(), p("replication.key")),
        ("PGSSLROOTCERT".into(), p("ca.crt")),
    ]
}

/// The statements run once on a new primary, over the local socket. The password reaches psql
/// on standard input, never on a command line.
pub fn bootstrap_sql(password: &str) -> String {
    format!(
        "ALTER ROLE {ADMIN_ROLE} WITH PASSWORD '{password}';\nCREATE ROLE {REPLICATION_ROLE} WITH LOGIN REPLICATION;\n"
    )
}

/// What the data directory holds.
#[derive(Debug, PartialEq, Eq)]
pub enum DataState {
    Empty,
    Primary,
    Standby,
}

pub fn data_state(data: &Path) -> Result<DataState, String> {
    let version = data.join("PG_VERSION");
    match std::fs::read_to_string(&version) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            let non_empty = std::fs::read_dir(data)
                .map(|mut d| d.next().is_some())
                .unwrap_or(false);
            if non_empty {
                Err(format!(
                    "{} is not empty but holds no PostgreSQL data",
                    data.display()
                ))
            } else {
                Ok(DataState::Empty)
            }
        }
        Err(e) => Err(format!("cannot read {}: {e}", version.display())),
        Ok(v) if v.trim() != "16" => {
            Err(format!("the data is for PostgreSQL {}, not 16", v.trim()))
        }
        Ok(_) => Ok(if data.join("standby.signal").exists() {
            DataState::Standby
        } else {
            DataState::Primary
        }),
    }
}

/// Refuses to start a node whose configuration disagrees with its data. A promoted standby
/// keeps running as a primary, and must not quietly go back to following the old one.
pub fn check_role(config: &NodeConfig, state: &DataState) -> Result<(), String> {
    match (config.role, state) {
        (_, DataState::Empty) => Ok(()),
        (Role::Primary, DataState::Primary) | (Role::Standby, DataState::Standby) => Ok(()),
        (Role::Primary, DataState::Standby) => Err(format!(
            "{} is configured as the primary but its data is a standby's. Promote it on purpose, then change the configuration.",
            config.node
        )),
        (Role::Standby, DataState::Primary) => Err(format!(
            "{} is configured as a standby but its data is a primary's, which looks like a promotion. Rebuild it from the current primary.",
            config.node
        )),
    }
}
